// provStore writes a small decision history: an alert, a limit raised in one
// transaction together with a note, then the limit changed again because of
// the note and a binary policy blob.
//
//	rev 1 alert           (ops-bot)
//	rev 2 limit=100       (sam, tx 2, cause alert@1)
//	rev 3 note            (sam, tx 2, cause alert@1)
//	rev 4 blob ff00       (ci)
//	rev 5 limit=150       (sam, cause note@3, blob@4)
func provStore(t *testing.T) (*DB, StoreID) {
	t.Helper()
	db, err := Open(filepath.Join(t.TempDir(), "p.xkv"), nil)
	if err != nil {
		t.Fatal(err)
	}
	t.Cleanup(func() { db.Close() })
	ctx := context.Background()
	must := func(_ Revision, err error) {
		if err != nil {
			t.Fatal(err)
		}
	}
	must(db.Put(ctx, "alert", []byte("latency high"), Reason("p99 over 2s"), Actor("ops-bot")))
	if err := db.Update(ctx, func(tx *Tx) error {
		if _, err := tx.Put("limit", []byte("100"), Reason("more headroom"), Actor("sam"), Ref("INC-1"), Cause("alert", 1)); err != nil {
			return err
		}
		_, err := tx.Put("note", []byte("raised for INC-1"), Reason("record it"), Actor("sam"), Cause("alert", 1))
		return err
	}); err != nil {
		t.Fatal(err)
	}
	must(db.Put(ctx, "blob", []byte{0xff, 0x00}, Reason("policy v2"), Actor("ci")))
	must(db.Put(ctx, "limit", []byte("150"), Reason("still short"), Actor("sam"), Cause("note", 3), Cause("blob", 4)))
	id, ok := db.StoreID()
	if !ok {
		t.Fatal("no store id")
	}
	return db, id
}

type provDoc struct {
	Context map[string]string `json:"@context"`
	Graph   []map[string]any  `json:"@graph"`
}

func provNodes(t *testing.T, b []byte) map[string]map[string]any {
	t.Helper()
	var d provDoc
	if err := json.Unmarshal(b, &d); err != nil {
		t.Fatalf("%v\n%s", err, b)
	}
	if d.Context["prov"] != "http://www.w3.org/ns/prov#" {
		t.Fatalf("context %v", d.Context)
	}
	out := map[string]map[string]any{}
	for _, n := range d.Graph {
		id := n["@id"].(string)
		if _, dup := out[id]; dup {
			t.Fatalf("node %s twice", id)
		}
		out[id] = n
	}
	return out
}

func ids(v any) []string {
	var out []string
	switch x := v.(type) {
	case map[string]any:
		out = append(out, x["@id"].(string))
	case []any:
		for _, y := range x {
			out = append(out, y.(map[string]any)["@id"].(string))
		}
	}
	return out
}

func TestPROV(t *testing.T) {
	db, id := provStore(t)
	n, err := db.Why(context.Background(), "limit", 0)
	if err != nil {
		t.Fatal(err)
	}
	b, err := n.PROV(id)
	if err != nil {
		t.Fatal(err)
	}
	again, _ := n.PROV(id)
	if !bytes.Equal(b, again) {
		t.Fatal("output differs between calls")
	}
	nodes := provNodes(t, b)
	rev := func(r uint64) string { return RevisionIRI(id, r) }
	tx := func(x uint64) string { return TransactionIRI(id, x) }
	e5 := nodes[rev(5)]
	if e5["@type"] != "prov:Entity" || e5["prov:value"] != "150" || e5["xkv:reason"] != "still short" || e5["xkv:key"] != "limit" {
		t.Fatalf("rev 5: %v", e5)
	}
	if got := ids(e5["prov:wasRevisionOf"]); len(got) != 1 || got[0] != rev(2) {
		t.Fatalf("wasRevisionOf %v", got)
	}
	if got := ids(e5["prov:wasDerivedFrom"]); strings.Join(got, " ") != rev(3)+" "+rev(4) {
		t.Fatalf("wasDerivedFrom %v", got)
	}
	if got := ids(e5["prov:wasAttributedTo"]); got[0] != AgentIRI("sam") {
		t.Fatalf("attributed %v", got)
	}
	// Tx 2 wrote rev 2 and rev 3; one activity, used alert@1 once.
	a2 := nodes[tx(2)]
	if a2["@type"] != "prov:Activity" || strings.Join(ids(a2["prov:used"]), " ") != rev(1) {
		t.Fatalf("tx 2: %v", a2)
	}
	if got := ids(nodes[rev(3)]["prov:wasGeneratedBy"]); got[0] != tx(2) {
		t.Fatalf("rev 3 generated by %v", got)
	}
	if nodes[rev(2)]["xkv:ref"] != "INC-1" {
		t.Fatalf("ref: %v", nodes[rev(2)])
	}
	// Binary values are base64.
	if e4 := nodes[rev(4)]; e4["prov:value"] != "/wA=" || e4["xkv:valueEncoding"] != "base64" {
		t.Fatalf("blob: %v", e4)
	}
	// Agents once each, sorted, after the rest.
	for _, a := range []string{"ci", "ops-bot", "sam"} {
		if nodes[AgentIRI(a)]["rdfs:label"] != a {
			t.Fatalf("agent %s missing", a)
		}
	}
	if len(nodes) != 5+4+3 { // revisions 1-5, transactions 1, 2, 3, 4, agents
		t.Fatalf("%d nodes", len(nodes))
	}
	if !strings.HasPrefix(nodes[rev(5)]["prov:generatedAtTime"].(map[string]any)["@type"].(string), "xsd:dateTime") {
		t.Fatal("time not typed")
	}
}

// One transaction can carry writes by different actors, and a write can name
// a revision from its own transaction as a cause.
func TestPROVMixedTransaction(t *testing.T) {
	db, err := Open(filepath.Join(t.TempDir(), "m.xkv"), nil)
	if err != nil {
		t.Fatal(err)
	}
	defer db.Close()
	ctx := context.Background()
	if err := db.Update(ctx, func(tx *Tx) error {
		if _, err := tx.Put("a", []byte("1"), Reason("first"), Actor("alice")); err != nil {
			return err
		}
		_, err := tx.Put("b", []byte("2"), Reason("follows a"), Actor("bob"), CauseLatest("a"))
		return err
	}); err != nil {
		t.Fatal(err)
	}
	if _, err := db.Put(ctx, "b", []byte("3"), Reason("again"), Actor("bob")); err != nil {
		t.Fatal(err)
	}
	id, _ := db.StoreID()
	n, err := db.WhyRev(ctx, 2, 0)
	if err != nil {
		t.Fatal(err)
	}
	b, _ := n.PROV(id)
	nodes := provNodes(t, b)
	a1 := nodes[TransactionIRI(id, 1)]
	agents := ids(a1["prov:wasAssociatedWith"])
	sort.Strings(agents)
	if got := strings.Join(agents, " "); got != AgentIRI("alice")+" "+AgentIRI("bob") {
		t.Fatalf("tx 1 agents: %s", got)
	}
	if a1["prov:used"] != nil {
		t.Fatalf("tx 1 used what it generated: %v", a1["prov:used"])
	}
	if got := ids(nodes[RevisionIRI(id, 2)]["prov:wasDerivedFrom"]); len(got) != 1 || got[0] != RevisionIRI(id, 1) {
		t.Fatalf("derivation lost: %v", got)
	}
	// The previous value of b@3 is shown without its causes, and says so.
	n, _ = db.Why(ctx, "b", 0)
	b, _ = n.PROV(id)
	nodes = provNodes(t, b)
	if nodes[RevisionIRI(id, 2)]["xkv:causesNotShown"] != true {
		t.Fatalf("prev: %v", nodes[RevisionIRI(id, 2)])
	}
}

func TestPROVDepthLimit(t *testing.T) {
	db, id := provStore(t)
	n, err := db.Why(context.Background(), "limit", 1)
	if err != nil {
		t.Fatal(err)
	}
	b, _ := n.PROV(id)
	nodes := provNodes(t, b)
	// Depth 1 shows rev 3 and 4 but not alert@1, which rev 3 names: it is a
	// bare entity marked unexplored, so every reference resolves.
	e1 := nodes[RevisionIRI(id, 1)]
	if e1["xkv:unexplored"] != true || e1["xkv:key"] != "alert" {
		t.Fatalf("rev 1: %v", e1)
	}
	if nodes[RevisionIRI(id, 3)]["xkv:truncated"] != true {
		t.Fatal("rev 3 not marked truncated")
	}
	for _, n := range nodes {
		for _, k := range []string{"prov:used", "prov:wasDerivedFrom", "prov:wasRevisionOf", "prov:wasGeneratedBy", "prov:wasAttributedTo", "prov:wasAssociatedWith"} {
			for _, ref := range ids(n[k]) {
				if _, ok := nodes[ref]; !ok {
					t.Fatalf("%s %s %s does not resolve", n["@id"], k, ref)
				}
			}
		}
	}
	// A cause with a name that needs escaping still gives a valid IRI.
	if got := AgentIRI("sam@oncall team/eu"); got != "urn:xkv:actor:sam@oncall%20team%2Feu" {
		t.Fatalf("agent IRI %s", got)
	}
}
