#!/usr/bin/env python3
"""Checks xkv's PROV output with rdflib, a JSON-LD and RDF library that
shares no code with xkv.

    python3 scripts/check-prov.py path/to/xkv

Builds a small store with the xkv command, exports a why tree with --prov,
parses it as JSON-LD and checks the triples PROV-O readers rely on.
Needs rdflib (pip install rdflib).
"""
import os
import subprocess
import sys
import tempfile

import rdflib
from rdflib.namespace import RDF

PROV = rdflib.Namespace("http://www.w3.org/ns/prov#")
XKV = rdflib.Namespace("https://xkv.org/ns#")

# PROV-O terms xkv may use; anything else under prov: is a mistake.
PROV_TERMS = {"Entity", "Activity", "Agent", "wasGeneratedBy", "wasAttributedTo", "wasAssociatedWith",
              "used", "wasDerivedFrom", "wasRevisionOf", "generatedAtTime", "endedAtTime", "value", "label"}


def run(xkv, *args):
    return subprocess.run([xkv, *args], check=True, capture_output=True, text=True).stdout


def main():
    xkv = os.path.abspath(sys.argv[1])
    with tempfile.TemporaryDirectory() as d:
        f = os.path.join(d, "s.xkv")
        run(xkv, "put", f, "alert", "latency high", "--reason", "p99 over 2s", "--actor", "ops-bot")
        run(xkv, "put", f, "limit", "100", "--reason", "more headroom", "--actor", "sam", "--cause", "alert@1", "--ref", "INC-1")
        run(xkv, "put", f, "limit", "150", "--reason", "still short", "--actor", "sam", "--cause", "alert")
        out = run(xkv, "why", f, "limit", "--prov")
    g = rdflib.Graph()
    g.parse(data=out, format="json-ld")
    store = None
    for s in g.subjects(RDF.type, PROV.Entity):
        store = str(s).split(":")[2]
    rev = lambda n: rdflib.URIRef(f"urn:xkv:{store}:rev:{n}")
    tx = lambda n: rdflib.URIRef(f"urn:xkv:{store}:tx:{n}")
    sam = rdflib.URIRef("urn:xkv:actor:sam")
    checks = [
        ((rev(3), RDF.type, PROV.Entity), "rev 3 is an entity"),
        ((rev(3), PROV.wasRevisionOf, rev(2)), "rev 3 revises rev 2"),
        ((rev(3), PROV.wasDerivedFrom, rev(1)), "rev 3 derives from the alert"),
        ((rev(3), PROV.wasGeneratedBy, tx(3)), "rev 3 generated by tx 3"),
        ((tx(3), RDF.type, PROV.Activity), "tx 3 is an activity"),
        ((tx(3), PROV.used, rev(1)), "tx 3 used the alert"),
        ((tx(3), PROV.wasAssociatedWith, sam), "tx 3 associated with sam"),
        ((rev(3), PROV.wasAttributedTo, sam), "rev 3 attributed to sam"),
        ((sam, RDF.type, PROV.Agent), "sam is an agent"),
        ((rev(3), XKV.reason, rdflib.Literal("still short")), "reason"),
        ((rev(2), XKV.ref, rdflib.Literal("INC-1")), "ref"),
        ((rev(3), PROV.value, rdflib.Literal("150")), "value"),
    ]
    failed = [msg for t, msg in checks if t not in g]
    for s, p, o in g:
        if str(p).startswith(str(PROV)) and str(p)[len(str(PROV)):] not in PROV_TERMS:
            failed.append(f"unknown PROV term {p}")
        if p == RDF.type and str(o).startswith(str(PROV)) and str(o)[len(str(PROV)):] not in PROV_TERMS:
            failed.append(f"unknown PROV class {o}")
    times = list(g.objects(rev(3), PROV.generatedAtTime))
    if len(times) != 1 or times[0].datatype != rdflib.XSD.dateTime or times[0].toPython() is None:
        failed.append("generatedAtTime is not one xsd:dateTime")
    # Every entity has a generating activity, every activity an agent.
    for e in g.subjects(RDF.type, PROV.Entity):
        if (e, XKV.unexplored, rdflib.Literal(True)) not in g and not list(g.objects(e, PROV.wasGeneratedBy)):
            failed.append(f"{e} has no wasGeneratedBy")
    for a in g.subjects(RDF.type, PROV.Activity):
        if not list(g.objects(a, PROV.wasAssociatedWith)):
            failed.append(f"{a} has no agent")
    if failed:
        print("PROV check failed:\n  " + "\n  ".join(failed))
        sys.exit(1)
    print(f"PROV check passed: {len(g)} triples, {len(checks)} expected triples present, only PROV-O terms used")


if __name__ == "__main__":
    main()
